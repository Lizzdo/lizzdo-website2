export const IconMapper = ({ name, ...props }: { name: string; [key: string]: any }) => {
  if (!name) {
    const FallbackComponent = Icons.HelpCircle;
    return <FallbackComponent {...props} />;
  }

  const siName = name.startsWith('Si') ? name : `Si${name.charAt(0).toUpperCase()}${name.slice(1)}`;

  const IconComponent =
    CustomIcons[name] ||
    (SimpleIcons as any)[name] ||
    (SimpleIcons as any)[siName] ||
    (Icons as any)[name] ||
    Icons.HelpCircle;

  return <IconComponent {...props} />;
};

